export const TAROT_CARD_MAP: Record<string, ITarotCard> = {};
for (const card of MOCK_TAROT_CARDS) {
  TAROT_CARD_MAP[card.id] = card;
}

/** 根据ID获取卡牌 */
export function getCardById(id: string): ITarotCard | undefined {
  return TAROT_CARD_MAP[id];
}

/** 根据分类获取卡牌列表 */
export function getCardsByCategory(category: ITarotCard['category']): ITarotCard[] {
  return MOCK_TAROT_CARDS.filter((c) => c.category === category);
}
